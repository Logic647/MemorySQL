import { describe, expect, it } from 'vitest'
import { firstRealUserMessage, isHarnessNoiseUserMessage } from '../src/shared/harness-noise'

/**
 * harness 注入噪声识别。样本全部来自真库(zcode 会话 #71/#571,2026-11-22)——
 * 各家 harness 把系统上下文/通知写成 user 角色,消费侧必须能认出来。
 * 「只标注不删除」:这里只测判定,不做任何数据改写。
 */
describe('isHarnessNoiseUserMessage', () => {
  it('识别 zcode/claude 系 harness 注入(真库实测样本)', () => {
    const noise = [
      '# Environment\nYou have been invoked in the following environment: \n - Primary working directory: C:\\',
      'You are powered by the model named account:zai-start-plan/GLM-5.3-Flash.',
      'The following deferred tools are available via LocalToolSearch. Use query "select:<name>"',
      'The following skills are available for use with the Skill tool:\n\n- academic-researcher',
      'The following MCP servers are configured but failed to connect',
      'Available agent types for the Agent tool:\n- documents:visual-judge: …',
      "The TodoWrite tool hasn't been used recently. If you are working on tasks that would benefit from TodoWrite",
      'The user hasn\'t heard from you in a while. As you continue, keep them updated when there is something to tell',
      'A plan file exists from plan mode at: H:\\桌面\\MemorySQL\\.zcode\\plans\\plan-sess_x.md',
      "Today's date is 2026-11-22.",
      'Caveat: The messages below were generated by the user while running local commands',
      'This session is being continued from a previous conversation that ran out of context.',
      'Codebase and user instructions are shown below. Be sure to adhere to these instructions.',
      "As you answer the user's questions, you can use the following context:",
      'Called the Read tool with the following input: {"file_path":"H:\\\\x.ts"}',
      'Result of calling the Read tool with the following input:',
      'Note: H:\\桌面\\MemorySQL\\docs\\DEVLOG.md was read before the last conversation was summarized',
      '[SYSTEM NOTIFICATION - NOT USER INPUT]\nThis is an automated background-task event',
      '<task-notification>\n<task-id>exec_c7ffeecc</task-id>\n<status>failed</status>',
      '<system-reminder>The TodoWrite tool hasn\'t been used recently</system-reminder>',
      '<total_tokens>15000000 tokens left</total_tokens>',
      '<local-command-stdout>(no content)</local-command-stdout>',
      '<user_instructions># AGENTS.md\n…',
      '<environment_context>cwd: /home/logic'
    ]
    for (const s of noise) expect(isHarnessNoiseUserMessage(s), JSON.stringify(s.slice(0, 40))).toBe(true)
  })

  it('不误伤真实用户输入(自然语言/斜杠命令/@引用/分享导入)', () => {
    const real = [
      '这四家怎么用命令行登录',
      '还有一个问题,会话记录好像没有用户输入的部分,检查一下',
      'Reply with exactly: ok',
      '/resume 44893c0e-ce39-4718-b7f6-60f9d0bf1954',
      '/plugin install superpowers@claude-plugins-official',
      'language /effort max',
      '@H:\\下载\\实验二 类与对象的使用.docx 根据文件里面第二项物联网智能风扇类SmartFan的要求对比我写的代码看看有没有要改进的',
      '# Shared conversation: 我想用nas上的显卡跑生图模型\n\n## User\n\n我想用nas上的显卡跑生图模型',
      '我先说结论:今天的日期还没定', // 用户自己谈日期
      '我的计划文件如下:\n- 第一步\n- 第二步', // 用户自述 plan,不含 harness 前缀话术
      '今天日期是 2026-11-22' // 中文,不同措辞
    ]
    for (const s of real) expect(isHarnessNoiseUserMessage(s), JSON.stringify(s.slice(0, 40))).toBe(false)
  })

  it('空消息不算噪声(由调用方另行处理)', () => {
    expect(isHarnessNoiseUserMessage('')).toBe(false)
    expect(isHarnessNoiseUserMessage('   \n  ')).toBe(false)
  })
})

describe('firstRealUserMessage', () => {
  it('跳过噪声取第一条真实输入;全噪声返回 null(宁缺毋滥)', () => {
    const env = '# Environment\nYou have been invoked in the following environment:'
    const msgs = [
      { role: 'user', content: env },
      { role: 'user', content: '<total_tokens>15000000 tokens left</total_tokens>' },
      { role: 'user', content: '帮我把语义检索的开关默认关掉' },
      { role: 'user', content: '谢谢' }
    ]
    expect(firstRealUserMessage(msgs)).toBe('帮我把语义检索的开关默认关掉')
    expect(firstRealUserMessage([{ role: 'user', content: env }])).toBeNull()
    // role 缺省按 user 处理(调用方已过滤过的数组)
    expect(firstRealUserMessage([{ content: '纯文本' }])).toBe('纯文本')
  })

  it('lookback 限流:开头一长串噪声不至于扫全表', () => {
    const noise = { role: 'user', content: 'Caveat: x' }
    const msgs = Array.from({ length: 20 }, () => noise)
    msgs.push({ role: 'user', content: '真实输入在第 21 条' })
    expect(firstRealUserMessage(msgs, 12)).toBeNull()
    expect(firstRealUserMessage(msgs, 50)).toBe('真实输入在第 21 条')
  })
})
